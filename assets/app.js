/**
 * Initialiser les icônes SVG dans la page
 */
function initIcons() {
    document.querySelectorAll('[data-icon]').forEach(element => {
        const iconName = element.getAttribute('data-icon');
        const width = element.getAttribute('data-icon-width') || '24';
        const height = element.getAttribute('data-icon-height') || '24';

        const icon = createSVGIcon(iconName, { width, height });
        element.innerHTML = '';
        element.appendChild(icon);
    });
}

/**
 * SMOOTH SCROLL - Pour les ancres de navigation
 */
function initSmoothScroll() {
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            const href = this.getAttribute('href');
            if (href === '#') return;

            e.preventDefault();
            const target = document.querySelector(href);

            if (target) {
                target.scrollIntoView({
                    behavior: 'smooth',
                    block: 'start'
                });
            }
        });
    });
}

/**
 * Mettre à jour le gradient du slider de prix
 */
function updatePriceSlider(slider) {
    const min = slider.min || 0;
    const max = slider.max || 100;
    const value = slider.value;

    // Calculer le pourcentage
    const percentage = ((value - min) / (max - min)) * 100;

    // Appliquer le gradient
    slider.style.background = `linear-gradient(to right, var(--bordeaux) 0%, var(--bordeaux) ${percentage}%, #e5e5e5 ${percentage}%, #e5e5e5 100%)`;
}

/**
 * GESTION DES FILTRES DU CATALOGUE - Figma Style
 * Note: Cette fonction est désactivée si le module AJAX est chargé (menu-filter-ajax.js)
 */
function initMenuFilters() {
    // Si le module AJAX est présent, ne pas initialiser cette fonction
    if (window.MenuFilterAjaxLoaded) {
        console.log('[app.js] Skipping initMenuFilters() - AJAX module is loaded');
        return;
    }

    const filterForm = document.getElementById('filterForm');
    const resetButton = document.getElementById('resetFilters');

    if (filterForm) {
        // Auto-submit du formulaire lors du changement de filtre
        const filterInputs = filterForm.querySelectorAll('input[type="range"], select, input[type="number"]');
        filterInputs.forEach(input => {
            if (input.type === 'range') {
                // Initialiser le gradient au chargement
                updatePriceSlider(input);

                // Mettre à jour le gradient pendant le drag
                input.addEventListener('input', () => {
                    updatePriceSlider(input);
                });

                // Pour le slider, attendre la fin du drag pour submit
                input.addEventListener('change', () => {
                    setTimeout(() => filterForm.submit(), 300);
                });
            } else {
                input.addEventListener('change', () => {
                    filterForm.submit();
                });
            }
        });

        // Gestion des boutons de régime alimentaire
        const regimeButtons = document.querySelectorAll('.regime-filter-btn[data-dietetary]');
        regimeButtons.forEach(button => {
            button.addEventListener('click', (e) => {
                e.preventDefault();
                const dietetaryId = button.getAttribute('data-dietetary');
                const checkbox = document.getElementById(`dietetary_${dietetaryId}`);

                if (checkbox) {
                    checkbox.checked = !checkbox.checked;
                    button.classList.toggle('active', checkbox.checked);

                    // Désactiver le bouton "Tous"
                    const allButton = document.querySelector('.regime-filter-btn:not([data-dietetary])');
                    if (allButton) allButton.classList.remove('active');

                    setTimeout(() => filterForm.submit(), 100);
                }
            });
        });

        // Bouton reset
        if (resetButton) {
            resetButton.addEventListener('click', (e) => {
                e.preventDefault();
                window.location.href = filterForm.action;
            });
        }
    }
}

/**
 * Fonction pour gérer le bouton "Tous" des régimes
 */
function clearDietetaryFilters(button) {
    const filterForm = document.getElementById('filterForm');
    if (!filterForm) return;

    // Décocher toutes les checkboxes de régime
    filterForm.querySelectorAll('input[name="dietetary[]"]').forEach(checkbox => {
        checkbox.checked = false;
    });

    // Retirer la classe active de tous les boutons de régime
    document.querySelectorAll('.regime-filter-btn').forEach(btn => {
        btn.classList.remove('active');
    });

    // Activer uniquement le bouton "Tous"
    button.classList.add('active');

    setTimeout(() => filterForm.submit(), 100);
}

// Rendre la fonction globale pour l'attribut onclick
window.clearDietetaryFilters = clearDietetaryFilters;

/**
 * ANIMATIONS AU SCROLL
 */
function initScrollAnimations() {
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('fade-in');
                observer.unobserve(entry.target);
            }
        });
    }, {
        threshold: 0.1,
        rootMargin: '0px 0px -50px 0px'
    });

    // Observer les éléments à animer
    document.querySelectorAll('.stat-card, .team-card, .testimonial-card').forEach(el => {
        observer.observe(el);
    });
}

